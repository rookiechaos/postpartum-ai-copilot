import React, { useEffect, useRef, useState } from 'react'
import { useTranslation } from 'react-i18next'
import api from '../utils/api'
import { useCareWork } from '../utils/CareSession'
import { revealElement } from '../utils/focusView'
import AIUseNotice from './AIUseNotice'
import SupportDirectory from './SupportDirectory'
import './NightMode.css'

const tabs = ['help', 'relaxation', 'breathing', 'safety']
const strings = value => Array.isArray(value) ? value.filter(item => typeof item === 'string') : []

function NightMode({ userId, onExit, visible = true, navigationRequest }) {
  const { t, i18n } = useTranslation()
  const language = (i18n.resolvedLanguage || i18n.language || 'ja').split('-')[0] === 'en' ? 'en' : 'ja'
  const [acceptedPayload, setAcceptedPayload] = useState(null)
  const [includeProfile, setIncludeProfile] = useState(false)
  const [query, setQuery] = useState('')
  const [queryVersion, setQueryVersion] = useState(0)
  const [response, setResponse] = useState(null)
  const [unreadResponse, setUnreadResponse] = useState(false)
  const [activeTab, setActiveTab] = useState('help')
  const [pending, setPending] = useState(null)
  const [errors, setErrors] = useState({})
  // Prepared guides are selected by the service, not generated by AI. Keep the
  // fetched language-specific version in this account's mounted session only.
  const [guides, setGuides] = useState({})
  const lock = useRef(false)
  const mounted = useRef(true)
  const sequence = useRef(0)
  const handledNavigation = useRef(null)
  const pendingFocus = useRef(null)
  const [focusVersion, setFocusVersion] = useState(0)
  const titleRef = useRef(null)
  const composerRef = useRef(null)
  const responseRef = useRef(null)
  const payload = { query: query.trim(), include_profile: includeProfile, include_records: false,
    urgency: 'high', language, night_mode: true }
  // The key is private to this component. Consent always names the exact current
  // question, attachment choice and language; it is never a blanket AI approval.
  const payloadKey = JSON.stringify(payload)
  const acceptedAI = acceptedPayload === payloadKey
  const loading = Boolean(pending)
  const reviewedPayload = pending?.tab === 'help' ? pending.payload : payload
  const currentGuide = guides[language]?.[activeTab]
  useEffect(() => {
    mounted.current = true
    return () => { mounted.current = false }
  }, [userId])
  useEffect(() => { setAcceptedPayload(null) }, [payloadKey, activeTab, visible])
  const workTitle = pending?.tab === 'help' ? 'nightFlow.workSending' : query.trim() ? 'nightFlow.workDraft' : null
  useCareWork('night-request', workTitle ? {
    version: `${queryVersion}:${pending?.sequence || 0}`, title: workTitle,
    critical: pending?.tab === 'help', protectLeave: true, priority: pending?.tab === 'help' ? 0 : 2,
    tab: 'night', detail: { action: 'resume' }, action: 'experience.trackedWorkOpen',
  } : null)
  useCareWork('night-result', unreadResponse && response ? {
    version: response.sequence, title: 'nightFlow.workResult', protectLeave: true, attention: true, priority: 1,
    tab: 'night', detail: { action: 'resume', target: 'result' }, action: 'nightFlow.viewResult',
  } : null)
  useEffect(() => {
    if (!visible || !navigationRequest?.key || handledNavigation.current === navigationRequest.key) return
    handledNavigation.current = navigationRequest.key
    const resultRequested = navigationRequest.target === 'result' && response
    if (resultRequested || query.trim() || pending?.tab === 'help') setActiveTab('help')
    pendingFocus.current = resultRequested ? 'result' : query.trim() || pending?.tab === 'help' ? 'composer' : 'title'
    setFocusVersion(value => value + 1)
  }, [navigationRequest?.key, visible])
  useEffect(() => {
    if (!visible || !pendingFocus.current) return
    const target = pendingFocus.current === 'result' ? responseRef.current
      : pendingFocus.current === 'composer' ? composerRef.current : titleRef.current
    if (revealElement(target)) {
      if (pendingFocus.current === 'result') setUnreadResponse(false)
      pendingFocus.current = null
    }
  }, [visible, activeTab, focusVersion])
  const updateQuery = value => {
    if (lock.current) return
    setQuery(value); setQueryVersion(version => version + 1); setAcceptedPayload(null)
  }
  const chooseTab = tab => {
    if (lock.current) return
    setActiveTab(tab); setAcceptedPayload(null)
  }
  const showResponse = () => {
    if (!response) return
    setActiveTab('help'); setAcceptedPayload(null)
    pendingFocus.current = 'result'; setFocusVersion(value => value + 1)
  }
  const handleCrisis = async () => {
    if (lock.current || !payload.query || !acceptedAI || activeTab !== 'help') return
    if (unreadResponse && !window.confirm(t('nightFlow.replaceUnread'))) return
    lock.current = true
    const operation = { tab: 'help', sequence: ++sequence.current, payload: { ...payload } }
    setPending(operation); setAcceptedPayload(null)
    setErrors(previous => ({ ...previous, help: null }))
    try {
      const result = await api.postCrisis(operation.payload)
      if (!mounted.current) return
      if (result?.error || typeof result?.response !== 'string' || !result.response.trim()) throw new Error('Unavailable response')
      setResponse({ response: result.response, actions: strings(result.actions), red_flags: strings(result.red_flags),
        payload: operation.payload, sequence: operation.sequence })
      setUnreadResponse(true)
      setQuery(''); setQueryVersion(version => version + 1)
    } catch (failure) {
      if (mounted.current) setErrors(previous => ({ ...previous, help: { uncertain: Boolean(failure.resultUnconfirmed), payload: operation.payload } }))
    } finally {
      lock.current = false
      if (mounted.current) { setPending(null); setAcceptedPayload(null) }
    }
  }
  const loadGuide = async tab => {
    if (lock.current || !['relaxation', 'breathing', 'safety'].includes(tab)) return
    lock.current = true
    const operation = { tab, sequence: ++sequence.current, language }
    setPending(operation); setAcceptedPayload(null)
    setErrors(previous => ({ ...previous, [tab]: null }))
    try {
      const result = tab === 'relaxation' ? await api.getNightModeRelaxation(operation.language)
        : tab === 'breathing' ? await api.getNightModeBreathing(operation.language)
          : await api.getNightModeSafetyTips(operation.language)
      if (!mounted.current) return
      const content = tab === 'relaxation' ? result?.guide : tab === 'breathing' ? result?.exercise : result
      if (!content || (tab === 'safety' ? !strings(content.tips).length
        : !(typeof (tab === 'relaxation' ? content.title : content.name) === 'string' && strings(content.steps).length))) {
        throw new Error('Unavailable guide')
      }
      setGuides(previous => ({ ...previous, [operation.language]: { ...previous[operation.language], [tab]: content } }))
    } catch {
      if (mounted.current) setErrors(previous => ({ ...previous, [tab]: { failed: true } }))
    } finally {
      lock.current = false
      if (mounted.current) { setPending(null); setAcceptedPayload(null) }
    }
  }
  const tabTitle = tab => t(tab === 'help' ? 'pilot.nightHelp' : `pilot.${tab}`)
  const languageLabel = value => value === 'en' ? 'English' : '日本語'
  const quickActions = ['babyCrying', 'babyWontSleep', 'isThisNormal', 'feedingConcerns', 'overwhelmed']
  return (
    <div className="night-mode" hidden={!visible}>
      <main className="night-mode-container" aria-labelledby="night-mode-title">
        <div className="night-mode-heading-row">
          <h1 id="night-mode-title" ref={titleRef} tabIndex={-1}>{t('nightMode.title')}</h1>
          <button type="button" className="exit-button" onClick={onExit}>{t('nightMode.exit')}</button>
        </div>
        <p>{t('nightMode.subtitle')}</p>
        <SupportDirectory compact visible={visible} />
        <div className="night-mode-tabs" role="group" aria-label={t('nightFlow.chooseView')}>
          {tabs.map(tab => <button type="button" key={tab} aria-pressed={activeTab === tab}
            aria-controls={`night-panel-${tab}`} disabled={loading}
            className={activeTab === tab ? 'active' : ''} onClick={() => chooseTab(tab)}>{tabTitle(tab)}</button>)}
        </div>
        <p className="night-mode-hint">{t('nightFlow.tabNotice')}</p>
        {unreadResponse && <div className="night-result-cue" role="status">
          <p>{t('nightFlow.resultReady')}</p><button type="button" onClick={showResponse}>{t('nightFlow.viewResult')}</button>
        </div>}
        {tabs.filter(tab => tab !== 'help').map(tab => <section key={tab} id={`night-panel-${tab}`} hidden={activeTab !== tab}
          aria-labelledby={`night-heading-${tab}`}>
          <h2 id={`night-heading-${tab}`}>{tabTitle(tab)}</h2>
          <p>{t(tab === 'safety' ? 'nightFlow.safetyNotice' : 'nightFlow.guideNotice')}</p>
          <button type="button" className="night-secondary" disabled={loading} onClick={() => loadGuide(tab)}>
            {pending?.tab === tab ? t('nightFlow.loadingGuide') : errors[tab] ? t('nightFlow.retryGuide')
              : currentGuide ? t('nightFlow.loadAgain') : t('nightFlow.loadGuide')}
          </button>
          {pending?.tab === tab && <p role="status">{t('nightFlow.loadingGuide')}</p>}
          {errors[tab] && <p role="alert">{t('nightFlow.guideError')}</p>}
          {activeTab === tab && currentGuide && <article className="night-guide">
            <p className="night-mode-hint">{t('nightFlow.cachedGuide', { language: languageLabel(language) })}</p>
            {tab === 'safety' ? <>
              {typeof currentGuide.emergency_message === 'string' && <p>{currentGuide.emergency_message}</p>}
              <ul>{strings(currentGuide.tips).map((tip, index) => <li key={index}>{tip}</li>)}</ul>
            </> : <>
              <h3>{tab === 'relaxation' ? currentGuide.title : currentGuide.name}</h3>
              {tab === 'relaxation' && typeof currentGuide.duration === 'string' && <p>{t('tracking.duration')}: {currentGuide.duration}</p>}
              {tab === 'breathing' && typeof currentGuide.description === 'string' && <p>{currentGuide.description}</p>}
              <ol>{strings(currentGuide.steps).map((step, index) => <li key={index}>{step}</li>)}</ol>
              {tab === 'breathing' && typeof currentGuide.benefits === 'string' && <p>{currentGuide.benefits}</p>}
            </>}
          </article>}
        </section>)}
        <section id="night-panel-help" hidden={activeTab !== 'help'} aria-labelledby="night-composer-heading">
          <h2 id="night-composer-heading" ref={composerRef} tabIndex={-1}>{t('pilot.nightHelp')}</h2>
          <p>{t('nightFlow.helpNotice')}</p>
          <details className="quick-actions"><summary>{t('nightMode.quickHelp')}</summary>
            <div className="quick-buttons">{quickActions.map(key => <button type="button" key={key} disabled={loading}
              className="quick-action-btn" onClick={() => {
                const next = t(`nightMode.${key}`)
                if (query.trim() && query !== next && !window.confirm(t('nightFlow.replaceQuestion'))) return
                updateQuery(next)
              }}>{t(`nightMode.${key}`)}</button>)}</div>
          </details>
          <label className="night-query-label" htmlFor="night-query">{t('nightFlow.question')}</label>
          <textarea id="night-query" value={query} rows={4} maxLength={5000} disabled={loading}
            onChange={event => updateQuery(event.target.value)} placeholder={t('nightMode.placeholder')}
            aria-describedby="night-query-hint" className="crisis-input-field" />
          <p id="night-query-hint" className="night-mode-hint">{t('nightFlow.inputHint')}</p>
          {query && <button type="button" className="night-secondary" disabled={loading} onClick={() => {
            if (window.confirm(t('nightFlow.clearQuestionConfirm'))) updateQuery('')
          }}>{t('nightFlow.clearQuestion')}</button>}
          <AIUseNotice scope="crisis" accepted={acceptedAI} onChange={value => {
            if (!lock.current) setAcceptedPayload(value ? payloadKey : null)
          }} disabled={loading} includeProfile={includeProfile} onProfileChange={value => {
            if (!lock.current) { setIncludeProfile(value); setAcceptedPayload(null) }
          }}>
            <section className="night-send-preview" aria-labelledby="night-preview-heading">
              <h3 id="night-preview-heading">{t('nightFlow.previewTitle')}</h3>
              <p>{t('nightFlow.previewNotice')}</p>
              <dl><div><dt>{t('nightFlow.question')}</dt><dd className="night-preserve-lines">{reviewedPayload.query || t('nightFlow.noQuestion')}</dd></div>
                <div><dt>{t('nightFlow.profile')}</dt><dd>{t(reviewedPayload.include_profile ? 'nightFlow.profileIncluded' : 'nightFlow.profileExcluded')}</dd></div>
                <div><dt>{t('nightFlow.records')}</dt><dd>{t('nightFlow.recordsExcluded')}</dd></div>
                <div><dt>{t('nightFlow.language')}</dt><dd>{languageLabel(reviewedPayload.language)}</dd></div>
                <div><dt>{t('nightFlow.answerStyle')}</dt><dd>{t('nightFlow.nightStyle')}</dd></div>
              </dl>
            </section>
          </AIUseNotice>
          {errors.help && <div className="night-request-error" role="alert"><p>{t(errors.help.uncertain ? 'nightFlow.sendUnconfirmed' : 'nightFlow.sendFailed')}</p>
            <p>{t('nightFlow.retryConsent')}</p>
            <details><summary>{t('nightFlow.failedQuestion')}</summary>
              <p className="night-preserve-lines">{errors.help.payload.query}</p>
              <p>{t('nightFlow.profile')}: {t(errors.help.payload.include_profile ? 'nightFlow.profileIncluded' : 'nightFlow.profileExcluded')}</p>
              <p>{t('nightFlow.language')}: {languageLabel(errors.help.payload.language)}</p>
            </details>
          </div>}
          <button type="button" className="crisis-submit-btn" onClick={handleCrisis} disabled={loading || !payload.query || !acceptedAI}>
            {pending?.tab === 'help' ? t('nightMode.gettingHelp') : t(errors.help ? 'nightFlow.retryHelp' : 'nightFlow.sendHelp')}
          </button>
          {pending?.tab === 'help' && <p role="status">{t('nightFlow.sending')}</p>}
          {response && <article className="crisis-response" aria-labelledby="night-response-heading">
            <h2 id="night-response-heading" ref={responseRef} tabIndex={-1}>{t('nightFlow.answerTitle')}</h2>
            <p>{t('pilot.aiLabel')}</p>
            {(pending?.tab === 'help' || errors.help) && <p className="night-mode-hint">{t('nightFlow.previousAnswer')}</p>}
            <details><summary>{t('nightFlow.sentQuestion')}</summary>
              <p className="night-preserve-lines">{response.payload.query}</p>
              <p>{t('nightFlow.profile')}: {t(response.payload.include_profile ? 'nightFlow.profileIncluded' : 'nightFlow.profileExcluded')}</p>
              <p>{t('nightFlow.language')}: {languageLabel(response.payload.language)}</p>
            </details>
            {response.red_flags.length > 0 && <section className="response-red-flags"><h3>{t('chat.important')}</h3>
              <ul>{response.red_flags.map((flag, index) => <li key={index}>{flag}</li>)}</ul></section>}
            <p className="response-text night-preserve-lines">{response.response}</p>
            {response.actions.length > 0 && <section className="response-actions"><h3>{t('nightMode.tryThis')}</h3>
              <ul>{response.actions.map((action, index) => <li key={index}>{action}</li>)}</ul></section>}
            <button type="button" className="night-secondary" disabled={loading} onClick={() => {
              if (!window.confirm(t('nightFlow.closeAnswerConfirm'))) return
              setResponse(null); setUnreadResponse(false)
            }}>{t('nightFlow.closeAnswer')}</button>
          </article>}
        </section>
        <p className="emergency-info"><strong>{t('nightMode.emergency')}</strong> {t('nightMode.emergencyText')}</p>
      </main>
    </div>
  )
}

export default NightMode
